/**
 * УДАР КАМНЕМ — две функции, из которых состоит вся физика броска.
 *
 * Живут отдельно от сцены и НЕ читают конфиг: числа приходят параметрами.
 * Иначе их нечем проверить — а проверять здесь есть что, потому что обе
 * ошибаются молча. Перепутанный знак в пружине не роняет ничего: слово просто
 * уезжает из кадра за пару кадров, и выглядит это как «сломался рендер».
 */

/**
 * Сила, с которой удар достаётся куску на расстоянии `distance` от попадания.
 *
 * Спад квадратичный, а не линейный: у линейного соседи точки попадания
 * получают почти столько же, сколько она сама, и вместо вмятины всё слово
 * вздрагивает целиком.
 */
export function impulse(distance: number, radius: number, strength: number): number {
  // Через отрицание, а не `distance >= radius`: NaN обязан дать ноль, а не
  // просочиться в позицию куска. Кусок с NaN исчезает навсегда — его матрица
  // перестаёт быть числом, и обратно он уже не вернётся ничем.
  if (!(distance < radius) || !(radius > 0)) return 0
  const f = 1 - distance / radius
  return strength * f * f
}

/**
 * Новая скорость пружины, тянущей кусок домой, за шаг `dt`.
 *
 * Полушаговый Эйлер: сначала обновляется скорость, потом ею двигают смещение.
 * Ровно в этом порядке — обратный порядок на тех же числах медленно
 * раскачивает пружину вместо того, чтобы её гасить.
 *
 * Возвращает одно число, а не пару и не вектор: функция зовётся шесть раз на
 * кусок каждый кадр, и любой возвращаемый объект — это несколько тысяч
 * мусорных аллокаций в секунду на ровном месте.
 */
export function springVelocity(
  offset: number,
  velocity: number,
  dt: number,
  stiffness: number,
  damping: number,
): number {
  return velocity + (-stiffness * offset - damping * velocity) * dt
}

/**
 * Вертикальная скорость свободно падающего обломка за шаг `dt`: тяжесть, пол,
 * отскок. Только вертикаль — по горизонтали обломок просто едет, там считать
 * нечего.
 *
 * Порог `snap` обязателен, и это не украшение. Отскок с любым коэффициентом
 * меньше единицы затухает геометрически: высота падает, но в ноль не приходит
 * НИКОГДА. Без порога камень до конца сеанса мелко дрожит на земле — на глаз
 * это читается как дребезг картинки, а не как лежащий камень.
 */
export function groundVelocity(
  y: number,
  vy: number,
  dt: number,
  gravity: number,
  floorY: number,
  restitution: number,
  snap: number,
): number {
  const next = vy - gravity * dt
  // Пол пробивается только вниз: летящий вверх обломок из земли не отражают.
  if (next >= 0 || y + next * dt > floorY) return next

  const back = -next * restitution
  if (back >= snap) return back

  // Отскок ниже порога — обломок ложится. Возвращается НЕ ноль, а скорость,
  // которая ставит его ровно на землю за этот шаг.
  //
  // Ноль оставил бы его висеть на волосок выше пола — расстояние
  // невидимое, но роковое: сцена узнаёт «обломок лёг» по тому, что он достал
  // до земли, и с этим волоском условие не срабатывает никогда. Обломок
  // замирает в воздухе в стадии падения и домой уже не возвращается.
  return (floorY - y) / dt
}
